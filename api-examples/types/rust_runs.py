"""Write a test that runs each Rust call that compiled, and read what the tests found.

compile_rust_types.py finds, for each option and held type, the cheapest call that compiles. This
module turns each of those calls into a test in rust_runs.rs. The test holds the option's value in
that type, passes it with that call, finishes the build or the encrypt, and checks the result:

  builds  the build or the call returned Ok
  same    the result matches the reference value: the bytes round trip, the reference keyring
          decrypts, or a getter returns the value
  copies  passing the value allocated at least as many bytes as it holds (plaintext and ciphertext)

Every test for an option holds the same value, so a type that changes the value shows as not the same.
rust_runs_support.rs has the reference values and the checks.
"""
