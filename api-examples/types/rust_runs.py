# A borrowed type is made from an owned one: [u8] from a Vec<u8>, str from a String.
BORROWED_FROM = {"[u8]": "Vec<u8>", "str": "String", "Path": "PathBuf", "[String]": "Vec<String>"}
# Types a test can't hold the value in, and why.
SKIP = {
    "char": "a char holds one letter, not the whole value",
    "TcpStream": "needs a network connection",
    "Option<&AppName>": "an AWS SDK name type, not text",
    "Option<&SigningRegionSet>": "an AWS SDK name type, not text",
}
NUMBERS = {"u8", "u16", "u32", "u64", "u128", "usize", "i8", "i16", "i32", "i64", "i128", "isize"}


def make(name, label, expr, values, out):
    """Append to `out` the lines that set `name` to the option's value held as `label`. Returns a skip reason or None.

    label is the type as the page shows it, and expr is the same type with full paths, for type annotations.
    """
    if label in SKIP:
        return SKIP[label]
    if label.startswith("Option<") and label.endswith(">"):
        why = make(name + "_inner", label[len("Option<"):-1], expr[len("Option<"):-1], values, out)
        if why:
            return why
        out.append(f"let {name} = Some({name}_inner);")
        return None
    if label == "&[&str]":
        why = make(name + "_text", "String", "String", values, out)
        if why:
            return why
        out.append(f"let {name}_list = [{name}_text.as_str()];")
        out.append(f"let {name}: &[&str] = &{name}_list;")
        return None
    if label.startswith("&"):
        inner = label[1:]
        owned = BORROWED_FROM.get(inner, inner)
        why = make(name + "_owned", owned, expr[1:] if owned == inner else owned, values, out)
        if why:
            return why
        out.append(f"let {name}: {expr} = &{name}_owned;")
        return None
    if label in NUMBERS:
        if "number" not in values:
            return "this option takes no number"
        article = "an" if label.startswith("i") else "a"
        out.append(f'let Ok({name}) = {label}::try_from({values["number"]}) else {{ r.skip("the value does not fit '
                   f'in {article} {label}"); return; }};')
        return None
    if label == "Duration" and "number" not in values:
        return "this option takes no duration"
    if label == "Duration":
        out.append(f"let {name} = std::time::Duration::from_secs({values['number']});")
        return None
    if re.fullmatch(r"\[u8; \d+\]", label):
        if "bytes" not in values:
            return "this option takes no bytes"
        size = label[len("[u8; "):-1]
        out.append(f"let {name}_bytes = {values['bytes']};")
        out.append(f'let Ok({name}) = <[u8; {size}]>::try_from({name}_bytes.as_slice()) else {{ '
                   f'r.skip("the value is not {size} bytes"); return; }};')
        return None
    template = OWNED.get(label)
    if template is None:
        return "no way to hold the value in this type yet"
    needs = set(re.findall(r"\{(\w)\}", template))
    fill = {}
    if "v" in needs:
        if "bytes" not in values:
            return "this option takes no bytes"
        fill["v"] = values["bytes"]
    if "t" in needs:
        text = values.get("value") or values.get("text")
        if text is None:
            return "this option takes no text"
        fill["t"] = text
    if "k" in needs:
        fill["k"] = values["key"]
    out.append(f"let {name} = {template.format(**fill)};")
    return None


def test_body(n, key, row, trial, recv, before, inline=False):
    """The lines of one test fn, or the lines of a test that only records why it was skipped.

    A test passes the value in its own statement, so it can count the bytes that passing allocates.
    With inline, the setter goes into the finishing statement instead, for a call whose argument
    borrows a temporary, like &std::fs::read(x).unwrap(). An inline test doesn't count copies.
    """
    spec = OPTIONS[key]
    label, kind = row["type"], row["kind"]
    _, _, expr, _, _, how, glue, _ = trial
    setter = setter_of(key)
    lines = ["#[tokio::test]", f"async fn run_{n}() {{",
             f"    // {key}: {label} passed as {row['code']}",
             f'    let mut r = Report::new("run_{n}");']
    setup = []
    if kind == "pair":
        # A pair holds the context's key as x and its value as y, both in the element type.
        element = label[1:-1].split(", ")[0]
        why = make("x", element, expr, {"text": spec["values"]["key"]}, setup) or \
            make("y", element, expr, {"text": spec["values"]["value"]}, setup)
    else:
        why = make("x", label, expr, spec["values"], setup)
    if why:
        return lines + [f'    r.skip("{why}");', "}"]
    lines += ["    " + s for s in setup]
    call = f".set_{setter}({glue})" if how == "set" else f".{setter}({glue})"
    lines.append(f"    let pre = {recv}{before};")
    if inline:
        first, *rest = spec["finish"]
        return lines + ["    " + first.replace("built", f"pre{call}", 1)] + ["    " + s for s in rest] + ["}"]
    if "size" in spec:
        lines += [f"    let size = {spec['size']};", "    let start = allocated();"]
    lines.append(f"    let built = pre{call};")
    if "size" in spec:
        lines.append("    r.copied(allocated() - start, size);")
    lines += ["    " + s for s in spec["finish"]]
    return lines + ["}"]


def setter_of(key):
    return key.split(".")[1]


def write(rows, trials, receivers, first_line, modes=None):
    """The text of rust_runs.rs, and {test name: (option, held type, line of the test fn)}.

    rows is {option: [row]} from compile_rust_types.py. A row's "trial" is its winning trial's line in
    rust_trials.rs, and first_line is the line of trials[0]. receivers is {option: (code that starts the
    call, part before the setter)}. modes maps a test name to "inline" (see test_body) or to "skip",
    for a test that only records that it didn't compile.
    """
    modes = modes or {}
    lines = list(HEADER)
    tests = {}
    for key in sorted(rows):
        if key not in OPTIONS:
            continue
        recv, before = receivers[key]
        for row in rows[key]:
            if row["calls"] is None:
                continue
            n = len(tests)
            name = f"run_{n}"
            lines.append("")
            tests[name] = (key, row["type"], len(lines) + 2)
            if modes.get(name) == "skip":
                lines += ["#[tokio::test]", f"async fn {name}() {{",
                          f"    // {key}: {row['type']} passed as {row['code']}",
                          f'    Report::new("{name}").skip("this test did not compile");', "}"]
                continue
            trial = trials[row["trial"] - first_line]
            lines += test_body(n, key, row, trial, recv, before, inline=modes.get(name) == "inline")
    return "\n".join(lines) + "\n", tests


def read(stdout):
    """{test name: findings} from the RUN lines that the tests print.

    The test harness prints "test run_0 ... " before a test's own output, so a RUN line can start mid-line.
    """
    found = {}
    for line in stdout.splitlines():
        m = re.search(r"RUN (run_\d+) (\{.*\})\s*$", line)
        if m:
            found[m.group(1)] = json.loads(m.group(2))
    return found
